@register.simple_tag
def icon(name, size=18, css_class=""):
    paths = ICONS.get(name, "")
    return format_html(
        '<svg class="icon {}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        css_class, size, size, mark_safe(paths),
    )


@register.filter
def initials(value):
    parts = str(value).replace("_", " ").replace(".", " ").replace("-", " ").split()
    if len(parts) == 1:  # single word: first two letters, e.g. ICTA -> IC, admin -> AD
        return parts[0][:2].upper()
    return "".join(p[0] for p in parts[:2]).upper() or "?"


@register.filter
def file_kind(filename):
    return str(filename).rsplit(".", 1)[-1].lower() if "." in str(filename) else "file"


@register.filter
def get(mapping, key):
    """{{ dict|get:key }} for lookups with a variable key."""
    return mapping.get(key, "") if hasattr(mapping, "get") else ""
